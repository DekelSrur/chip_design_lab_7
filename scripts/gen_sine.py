#!/usr/bin/env python3
"""Generate src/rom.sv - sine look-up table for the Lab 7 DDS.

The table is written straight into rom.sv as a constant array (same style as
black_magic_box.sv), so no .mem file has to be added to the Vivado project.

One full period, DEPTH entries, unsigned WIDTH-bit values.
Raised-cosine shape: starts at 0 (LED dark), peaks at DEPTH/2, back to 0.
    value[i] = round( MAX * (1 - cos(2*pi*i/DEPTH)) / 2 )

Usage:  python scripts/gen_sine.py            -> writes src/rom.sv
"""
import math
from pathlib import Path

DEPTH = 512          # = 2**9, matches the 9-bit init_phase
WIDTH = 8            # values 0..255
MAX   = 2**WIDTH - 1
PER_LINE = 16

values = [round(MAX * (1 - math.cos(2 * math.pi * i / DEPTH)) / 2) for i in range(DEPTH)]

rows = []
for i in range(0, DEPTH, PER_LINE):
    chunk = ", ".join(f"{WIDTH}'d{v:3d}" for v in values[i:i + PER_LINE])
    sep = "," if i + PER_LINE < DEPTH else ""
    rows.append(f"        {chunk}{sep}   // {i:3d}..{i + PER_LINE - 1:3d}")

ADDR_W = (DEPTH - 1).bit_length()

sv = f"""`timescale 1ns/1ps

// ROM - sine look-up table for the DDS
// {DEPTH} entries of one full period, unsigned {WIDTH}-bit values (0 = dark, {MAX} = peak).
// The table is a constant array, like black_magic_box.sv - no .mem file needed.
// Synchronous read: data is valid one clock after addr.
//
// GENERATED by scripts/gen_sine.py - edit the script, not this file.

module rom #(
    parameter int  DEPTH  = {DEPTH},                 // must match the table below
    parameter int  WIDTH  = {WIDTH},
    localparam int ADDR_W = $clog2(DEPTH)
)(
    input  logic              clk,
    input  logic [ADDR_W-1:0] addr,                   // phase
    output logic [WIDTH-1:0]  data                    // wave
);

    // elaboration-time check (no hardware)
    generate
        if (DEPTH != {DEPTH} || WIDTH != {WIDTH}) begin : G_SIZE_CHECK
            $error("rom: the sine table is {DEPTH} x {WIDTH} - regenerate it with scripts/gen_sine.py");
        end
    endgenerate

    // raised cosine: value[i] = round({MAX} * (1 - cos(2*pi*i/{DEPTH})) / 2)
    const logic [WIDTH-1:0] SINE_TABLE [0:DEPTH-1] = '{{
{chr(10).join(rows)}
    }};

    always_ff @(posedge clk) data <= SINE_TABLE[addr];

endmodule
"""

out = Path(__file__).resolve().parent.parent / "src" / "rom.sv"
out.write_text(sv)
print(f"wrote {DEPTH} x {WIDTH}-bit sine table -> {out}")
